#!/usr/bin/env python3
"""Emit large_inputs_nisb's six run configs and the data configs they read, from one template.

The arms are {1, 3, 5} NISB base training cubes x {256^3, 512^3} windows, and the claim the
experiment rests on is that they differ in nothing else. So nothing is hand-maintained: every
setting is written once below, and an arm is a window from WINDOWS plus a cube count from CUBES.
Regenerate after any edit and read the `git diff`:

    python experiments/large_inputs_nisb/make_configs.py

The claim can be checked directly:

    diff <(grep -v '^#' w256_1cube.toml) <(grep -v '^#' w512_5cube.toml)

prints the experiment name, the training data and the window's lines, and nothing else.
"""
import pathlib

HERE = pathlib.Path(__file__).parent
REL = "experiments/large_inputs_nisb"
NISB = "/groups/miaai/miaai/lmd-v0.0.1/dev/nisb/base"

# The 5 base cubes, taken in seed order so the arms are nested subsets, as in data_scaling.
CUBES = (1, 3, 5)

# Per window: the crop (x, y, z voxels, output_axes "lcxyz") and the lines that follow from it.
WINDOWS = {
    "w256": dict(
        doc="256^3",
        patch="[256, 256, 256]",
        img_size="256                # 16^3 = 4,096 tokens: 2.3 x 2.3 x 5.1 um",
        decode_chunks="1           # undivided, as 5a",
        checkpointing="false  # as 5a",
    ),
    "w512": dict(
        doc="512^3",
        patch="[512, 512, 512]",
        img_size="512                # 32^3 = 32,768 tokens: 4.6 x 4.6 x 10.2 um",
        decode_chunks="4           # 8-plane slabs: under cuDNN's 2^31, 3% faster than 3",
        checkpointing="false  # as 5a",
    ),
}

RUN = '''# large_inputs_nisb arm {arm}: {n} NISB base training cube{s} at a {doc} window.
# GENERATED by make_configs.py -- edit there, not here.
#
# Does adding labelled cubes help more at a larger window? data_scaling found 1 -> 3 -> 5 cubes flat
# at 256^3 (whole-cube nERL 0.423 / 0.431 / 0.391). This repeats that series at 256^3 and at 512^3
# with one model (README.md).
#
# The model is gary_comparison arm 5a: the released DINOv3 ViT-L/16 (LVD-1689M), inflated to 3D,
# trained with `affinity_seg` and the UNETR decoder for 500k steps, global attention in every block.
# Two changes, requested 2026-10-02: batch 1 per rank x 8 ranks (5a ran 4 x 2, the same global
# batch 8), and a checkpoint every 100k (5a: 50k). A third, 2026-10-03: attention scores capped at
# 1e5 (`attn_max_score`; README.md, "Attention score cap").
#
# Launch through submit.sh. It exports TORCHINDUCTOR_LAYOUT_OPTIMIZATION=0, without which inductor's
# layout optimisation and the head's voxel-resolution convolutions kill compiled runs at step 1, and
# writes runs to /nrs/scicompsoft/orhane/mia-train-experiments/large_inputs_nisb/runs.
experiment_name = "large_inputs_nisb__{arm}"

[model]
name = "dinov3_vit3d"
img_size = {img_size}
patch_size = 16
in_chans = 1
embed_dim = 1024          # ViT-L/16, 303M parameters
depth = 24
num_heads = 16
n_storage_tokens = 4
layerscale_init = 1.0e-05 # NOT optional: the released weights were trained with LayerScale
mask_k_bias = true
pos_embed_rope_dtype = "fp32"
pos_embed_rope_type = "vanilla"
drop_path_rate = 0.0      # DINOv3 drops whole samples, so at 1 per rank this drops nothing
use_fa4 = false           # torch SDPA: FA4 cannot be combined with compile
# Every attention score at most 1e5, by capping the lengths of queries and keys. Inactive at the
# start (the released model needs 1.6e4); the first launch grew block 0's scores to 3e8, where the
# fused kernels' gradients are wrong (README.md, "Attention score cap").
attn_max_score = 1e5

[init]
path = "/groups/miaai/miaai/pretrained_models/dinov3/dinov3_vitl16_pretrain_lvd1689m-8aa4cbdd.pth"
inflate_2d_to_3d = true   # the (1024,3,16,16) patch kernel, averaged over RGB and spread over z
skip = ["rope_embed."]    # a 2D checkpoint says nothing about z; the 3D RoPE tables are rebuilt
strict = true

[algorithm]
name = "affinity_seg"
long_range = 10
decoder = "unetr"
decoder_skip_layers = [5, 11, 17, 23]  # 0-based: blocks 6/12/18/24, ending each quarter
decoder_widths = [16, 32, 64, 128]     # channels at strides 1/2/4/8
decoder_image_skip = true
decoder_zero_init_output = false
split_disconnected = true
decode_chunks = {decode_chunks}

[data]
name = "miao_volumes"
config_path = "{rel}/data/nisb_base_train_{n}cube.yaml"
patch_size = {patch}  # x, y, z voxels: the window
samples_per_epoch = 100000  # 12.5k steps per epoch; each epoch end respawns the workers
defer_image_ops = true

[val_data]
# seed100, the base validation cube, in every arm, at the arm's own window: RoPE normalises
# positions by the window, so the model only ever runs at the size it trained at.
name = "miao_volumes"
config_path = "{rel}/data/nisb_base_val.yaml"
patch_size = {patch}
samples_per_epoch = 32
defer_image_ops = true

[trainer]
max_steps = 500000
batch_size = 1            # per rank; x 8 ranks -> global batch 8
lr = 0.0003
warmup_steps = 5000
min_lr_ratio = 0.001
weight_decay = 0.05
grad_clip_norm = 1.0
layerwise_lr_decay = 1.0
patch_embed_lr_mult = 1.0
lr_schedule = "linear"
precision = "bf16"
compile = true
activation_checkpointing = {checkpointing}
log_every = 1000
val_every = 10000
checkpoint_every = 100000
num_workers = 11          # 12 slots per GPU = 1 + 11
seed = 0

[parallelism]
dp_replicate = 1
dp_shard = 8              # one full B300 node per arm
tp = 1

[augment]
rotate = "inplane"        # the 16 transforms that keep z the sectioning axis
drop_slice_prob = 0.05
shift_slice_prob = 0.05
shift_magnitude = 10
intensity = true
mul_intensity = 0.1
add_intensity = 0.1
noise_scale = 0.5
'''

DATA_HEAD = '''# large_inputs_nisb {what}. GENERATED by make_configs.py.
#
# Copied 2026-10-02 from {source} (mia-train 36ff8f6),
# with defer_image_ops added. {cubes}
#
# 9x9x20 nm is the stored level-0 voxel, so miao reads level 0 and resamples nothing. x, y, z is the
# stores' own axis order. Each cube is 3000 x 3000 x 1350 voxels, 27 um on every side.
resolutions: [[9, 9, 20]]
output_axes: lcxyz
# miao validates this file as a whole config before the run config's keys override it, so it needs a
# patch_size. The window is what the arms vary: each arm's TOML sets its own, and that is what runs.
patch_size: [256, 256, 256]
samples_per_epoch: 1000   # the run config overrides this
defer_image_ops: true
volumes:
'''

VOLUME = '''  - name: NISB base {seed}
    path: {path}
    image_key: raw
    label_key: labels/public_gt-cell-nisb
    zarr_version: zarr3
    weight: {weight}
    normalize: true   # uint8 on disk, so this maps to [0, 1] by dtype max
'''


def volume(split: str, seed: str, weight: float) -> str:
    return VOLUME.format(seed=seed, path=f"{NISB}/{split}/{seed}.zarr", weight=weight)


(HERE / "data").mkdir(exist_ok=True)
for n in CUBES:
    head = DATA_HEAD.format(
        what=f"training data: the first {n} of NISB base's 5 training cubes",
        source=f"experiments/data_scaling/nisb_base_{n}cube_256.yaml",
        cubes="The cube sets are data_scaling's:\n# nested, in seed order "
              "(seed0; seed0-2; seed0-4), with equal weights.",
    )
    body = "".join(volume("train", f"seed{i}", round(1 / n, 6)) for i in range(n))
    (HERE / "data" / f"nisb_base_train_{n}cube.yaml").write_text(head + body)
    print(f"wrote data/nisb_base_train_{n}cube.yaml")
head = DATA_HEAD.format(
    what="validation data: NISB base's validation cube, seed100, for every arm",
    source="experiments/data_scaling's [val_data]",
    cubes="Model selection only: the test cube\n# (seed101) is mia-evals' and is never read here.",
)
(HERE / "data" / "nisb_base_val.yaml").write_text(head + volume("val", "seed100", 1.0))
print("wrote data/nisb_base_val.yaml")

for tag, window in WINDOWS.items():
    for n in CUBES:
        arm = f"{tag}_{n}cube"
        text = RUN.format(arm=arm, n=n, s="" if n == 1 else "s", rel=REL, **window)
        (HERE / f"{arm}.toml").write_text(text)
        print(f"wrote {arm}.toml")
