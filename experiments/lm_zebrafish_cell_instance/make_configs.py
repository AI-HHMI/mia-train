#!/usr/bin/env python3
"""Emit lm_zebrafish_cell_instance's four run configs and the data config they read, from one template.

The arms are two windows x the serial-section EM augmentations on or off, and they differ in nothing
else. So nothing is hand-maintained: every setting is written once below, and an arm is a window from
WINDOWS plus a setting from AUGMENTS. Regenerate after any edit and read the `git diff`:

    python experiments/lm_zebrafish_cell_instance/make_configs.py

The claim can be checked directly:

    diff <(grep -v '^#' w288_noem.toml) <(grep -v '^#' w496_em.toml)

prints the experiment name, the window's lines and the two augmentation probabilities, and nothing else.
"""
import pathlib

HERE = pathlib.Path(__file__).parent
REL = "experiments/lm_zebrafish_cell_instance"
STORE = (
    "/groups/miaai/miaai/lmd-v0.0.1/data/lm-zebrafish-Betzig-mosaic-example_annotations_Thayer/"
    "crop-001_dsr_timeseries_48t_1c.zarr"
)

# Per window: the crop (x, y, z voxels, output_axes "lcxyz") and the lines that follow from it. z is 144
# in both, the largest multiple of the 16-voxel patch inside a 152-slice frame; x == y because
# rotate = "inplane" exchanges them.
WINDOWS = {
    "w496": dict(
        doc="496 x 496 x 144",
        patch="[496, 496, 144]",
        img_size="[496, 496, 144]    # 31 x 31 x 9 = 8,649 tokens: 53.6 x 53.6 x 28.8 um",
    ),
    "w288": dict(
        doc="288 x 288 x 144",
        patch="[288, 288, 144]",
        img_size="[288, 288, 144]    # 18 x 18 x 9 = 2,916 tokens: 31.1 x 31.1 x 28.8 um",
    ),
}

# The serial-section EM artefacts large_inputs_nisb trains with (dropped and shifted sections,
# data/augment.py), on or off. Everything else in [augment] is the same in every arm.
AUGMENTS = {
    "em": dict(
        doc="with the serial-section EM augmentations",
        drop="0.05",
        shift="0.05",
        note="ON, as large_inputs_nisb",
    ),
    "noem": dict(
        doc="without the serial-section EM augmentations",
        drop="0.0",
        shift="0.0",
        note="OFF",
    ),
}

RUN = '''# lm_zebrafish_cell_instance arm {arm}: a {window_doc} window, {aug_doc}.
# GENERATED by make_configs.py -- edit there, not here.
#
# An affinity model for mia-evals' lm_zebrafish_cell_instance task: cells in one frame of a light-sheet
# zebrafish time series, 200 x 108 x 108 nm voxels (README.md). Trained on the task's fit frames, 1 and
# 25; frame 10 is the test frame and is never read here. No validation (user, 2026-10-12).
#
# The recipe is large_inputs_nisb__w512_5cube's config (gary_comparison arm 5a: the released DINOv3
# ViT-L/16, LVD-1689M, inflated to 3D, global attention in every block, `affinity_seg` with the UNETR
# decoder, attention scores capped at 1e5). Its checkpoint is not used: every arm starts from the
# released weights. Changed (2026-10-12): the data and window, no [val_data], 100k steps with a
# checkpoint every 10k, and an undivided decode (the window is under a third of 512^3).
#
# Launch through submit.sh. It exports TORCHINDUCTOR_LAYOUT_OPTIMIZATION=0, without which inductor's
# layout optimisation and the head's voxel-resolution convolutions kill compiled runs at step 1, puts
# a pinned miao 0.4.2 on PYTHONPATH (fixed_axes; myvenv's 0.4.1 cannot read the store's frames), and
# writes runs to /nrs/scicompsoft/orhane/mia-train-experiments/lm_zebrafish_cell_instance/runs.
experiment_name = "lm_zebrafish_cell_instance__{arm}"

[model]
name = "dinov3_vit3d"
img_size = {img_size}
patch_size = 16
in_chans = 1
embed_dim = 1024          # ViT-L/16, 303M parameters
depth = 24
num_heads = 16
n_storage_tokens = 4
layerscale_init = 1.0e-05 # NOT optional: the released weights were trained with LayerScale
mask_k_bias = true
pos_embed_rope_dtype = "fp32"
pos_embed_rope_type = "vanilla"
drop_path_rate = 0.0      # DINOv3 drops whole samples, so at 1 per rank this drops nothing
use_fa4 = false           # torch SDPA: FA4 cannot be combined with compile
# Every attention score at most 1e5, by capping the lengths of queries and keys. Inactive at the
# start (the released model needs 1.6e4); without it, large_inputs_nisb's first launch grew block 0's
# scores to 3e8, where the fused kernels' gradients are wrong.
attn_max_score = 1e5

[init]
path = "/groups/miaai/miaai/pretrained_models/dinov3/dinov3_vitl16_pretrain_lvd1689m-8aa4cbdd.pth"
inflate_2d_to_3d = true   # the (1024,3,16,16) patch kernel, averaged over RGB and spread over z
skip = ["rope_embed."]    # a 2D checkpoint says nothing about z; the 3D RoPE tables are rebuilt
strict = true

[algorithm]
name = "affinity_seg"
long_range = 10
decoder = "unetr"
decoder_skip_layers = [5, 11, 17, 23]  # 0-based: blocks 6/12/18/24, ending each quarter
decoder_widths = [16, 32, 64, 128]     # channels at strides 1/2/4/8
decoder_image_skip = true
decoder_zero_init_output = false
split_disconnected = true
decode_chunks = 1           # undivided, as large_inputs_nisb's 256^3 arms (16.8 M voxels, 18.5 GiB)

[data]
name = "miao_volumes"
config_path = "{rel}/data/train.yaml"
patch_size = {patch}  # x, y, z voxels: the window
samples_per_epoch = 100000  # 12.5k steps per epoch; each epoch end respawns the workers
defer_image_ops = true

[trainer]
max_steps = 100000
batch_size = 1            # per rank; x 8 ranks -> global batch 8
lr = 0.0003
warmup_steps = 5000
min_lr_ratio = 0.001
weight_decay = 0.05
grad_clip_norm = 1.0
layerwise_lr_decay = 1.0
patch_embed_lr_mult = 1.0
lr_schedule = "linear"
precision = "bf16"
compile = true
activation_checkpointing = false
log_every = 1000
checkpoint_every = 10000
num_workers = 11          # 12 slots per GPU = 1 + 11
seed = 0

[parallelism]
dp_replicate = 1
dp_shard = 8              # one full B300 node per arm
tp = 1

[augment]
rotate = "inplane"        # the 16 transforms that keep z (200 nm) in place; x and y swap, so x == y
# Dropped and shifted sections, the serial-section EM artefacts: {aug_note}.
drop_slice_prob = {drop}
shift_slice_prob = {shift}
shift_magnitude = 10
intensity = true
mul_intensity = 0.1
add_intensity = 0.1
noise_scale = 0.5
'''

DATA = f'''# lm_zebrafish_cell_instance training data: frames 1 and 25 of the Betzig light-sheet zebrafish time
# series. GENERATED by make_configs.py.
#
# Copied 2026-10-12 from mia-evals configs/lm_zebrafish_cell_instance/data/fit.yaml (mia-evals 3e6cd5a),
# the task's fit split; its header explains the labels and frame 1's box. Changed:
#   - output_axes lczyx -> lcxyz, because affinity_seg defines its targets in x, y, z order. miao reads
#     resolutions AND bounding_box in output_axes order, so both are rewritten as x, y, z below;
#   - patch_size, a placeholder (below);
#   - equal explicit weights.
#
# The store holds 48 frames as t, c, z, y, x, and fixed_axes pins one per entry. That needs miao >= 0.4.2,
# which submit.sh puts on PYTHONPATH (myvenv's 0.4.1 has no fixed_axes). Frame 10, the task's test frame,
# is never read here.
resolutions: [[108.0, 108.0, 200.0]]   # x, y, z in nm (output_axes order)
output_axes: lcxyz
# miao validates this file as a whole config before the run config's keys override it, so it needs a
# patch_size. The window is what the arms vary: each arm's TOML sets its own, and that is what runs.
patch_size: [288, 288, 144]
samples_per_epoch: 1000   # the run config overrides this
defer_image_ops: true
volumes:
  - name: lm_zebrafish_t01
    path: {STORE}
    image_key: raw
    label_key: labels/postprocessed_labels_t01
    zarr_version: zarr3
    fixed_axes: {{t: 1}}
    weight: 0.5
    normalize_min: 715
    normalize_max: 16923
    # x, y, z: past the strip (z = 0, y < 5, x < 5) that the label's re-registration left unlabelled
    bounding_box: [[5, 1466], [5, 508], [1, 152]]
  - name: lm_zebrafish_t25
    path: {STORE}
    image_key: raw
    label_key: labels/manual_gt-cell-t25_postproofread
    zarr_version: zarr3
    fixed_axes: {{t: 25}}
    weight: 0.5
    normalize_min: 715
    normalize_max: 16923
    bounding_box: [[0, 1466], [0, 508], [0, 152]]   # x, y, z: the whole frame
'''

(HERE / "data").mkdir(exist_ok=True)
(HERE / "data" / "train.yaml").write_text(DATA)
print("wrote data/train.yaml")

for tag, window in WINDOWS.items():
    for aug, augment in AUGMENTS.items():
        arm = f"{tag}_{aug}"
        text = RUN.format(
            arm=arm, rel=REL, window_doc=window["doc"], patch=window["patch"],
            img_size=window["img_size"], aug_doc=augment["doc"], drop=augment["drop"],
            shift=augment["shift"], aug_note=augment["note"],
        )
        (HERE / f"{arm}.toml").write_text(text)
        print(f"wrote {arm}.toml")
