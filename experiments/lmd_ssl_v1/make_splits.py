#!/usr/bin/env python3
"""Split the 8-volume instance-segmentation eval set 4/4 into finetune and validation configs.

The 8 volumes fall into four natural pairs -- two Kasthuri blocks, two zebrafish crops, two LICONN
manual-GT volumes, and two "one of a kind" volumes -- so taking one of each pair puts every modality
on both sides of the split. A split that put, say, all the ExM on one side would measure
cross-modality transfer instead of segmentation quality, which is a different question.

AC3-train / AC4-val is also the conventional Kasthuri protocol, and the two zebrafish crops come
from different coordinates in the same volume, so no pair overlaps spatially.

Volume-wise rather than within-volume: a within-volume split has to subdivide each annotated
bounding box, and measured against the real boxes that is infeasible at patch 256 for the
multi-scale variant -- `bounding_box` must contain the COARSEST window (256 x 32 nm = 8192 nm per
axis), and only 2 of 8 boxes can hold two disjoint copies of that. Volume-wise keeps every box
whole, so both variants work at patch 256 with the ladders the eval configs already validated.

    python experiments/lmd_ssl_v1/make_splits.py
"""
import sys
from pathlib import Path

import yaml

CONFIGS = Path("/groups/miaai/miaai/lmd-v0.0.1/configs/evals/v1/instance_seg")
HERE = Path(__file__).resolve().parent

FINETUNE = [
    "kasthuri15_ac3",              # mouse cortex ssTEM 6x6x29 nm
    "zebrafish_fish2_quadcube1",   # zebrafish brain EM 8x8x7.5 nm
    "liconn_mouse_dg",             # mouse dentate gyrus ExM ~10x10x25 nm
    "hemibrain_ellipsoid_body",    # Drosophila EM 8 nm isotropic
]
VALIDATION = [
    "kasthuri15_ac4",
    "zebrafish_fish2_doublecube1",
    "liconn_mouse_hippocampus",
    "liconn_expid82",              # mouse ExM at connectomic scale
]


def main() -> int:
    for variant in ("singlescale", "multiscale"):
        src = CONFIGS / f"lmd_instance_seg_eval_{variant}_patch256.yaml"
        cfg = yaml.safe_load(src.read_text())
        by_name = {v["name"]: v for v in cfg["volumes"]}
        missing = set(FINETUNE + VALIDATION) - set(by_name)
        if missing:
            print(f"ERROR: {src.name} has no volume(s) {sorted(missing)}; the eval set changed "
                  f"and this split must be revisited. Present: {sorted(by_name)}", file=sys.stderr)
            return 1

        globals_ = {k: v for k, v in cfg.items() if k != "volumes"}
        for split, names in (("finetune", FINETUNE), ("val", VALIDATION)):
            vols = [dict(by_name[n]) for n in names]
            # Equal weight per volume. Size-proportional would send ~80% of finetuning to the
            # zebrafish crop, which holds 50x Kasthuri's voxels; the point of the split is that
            # every modality is represented, so weight them equally.
            for v in vols:
                v["weight"] = round(1.0 / len(vols), 6)
            body = (
                f"# {split} split of the lmd instance-segmentation eval set -- {variant}.\n"
                f"#\n"
                f"# GENERATED by experiments/lmd_ssl_v1/make_splits.py from\n"
                f"#   {src}\n"
                f"# Do not edit by hand.\n"
                f"#\n"
                f"# {len(vols)} volumes, one per modality pair, equally weighted. The complementary\n"
                f"# split is lmd_{'val' if split == 'finetune' else 'finetune'}_{variant}.yaml.\n"
                f"# Every entry keeps the bounding box measured from its label's non-zero extent --\n"
                f"# LICONN DG and hippocampus have 0% GT in their own central 256^3 block, so\n"
                f"# dropping the box would train and score on unannotated space.\n"
                "#\n"
                + "".join(f"#   {v['name']}\n" for v in vols)
                + "\n"
                + yaml.safe_dump(globals_, sort_keys=False, default_flow_style=False)
                + "\n"
                + yaml.safe_dump({"volumes": vols}, sort_keys=False, default_flow_style=False)
            )
            out = HERE / f"lmd_{split}_{variant}.yaml"
            out.write_text(body)
            print(f"wrote {out.name}: {len(vols)} volumes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
