#!/usr/bin/env bash
# Submit the pseudo-labelling bootstrap. Two arms, two rounds each, with a pseudo-labelling job
# between the rounds.
#
#   bash experiments/pseudo_labeling/submit.sh              # everything
#   bash experiments/pseudo_labeling/submit.sh --label r1   # only generate round 1's labels
#   bash experiments/pseudo_labeling/submit.sh 1            # only arm 1 (assumes r1 labels exist)
#   bash experiments/pseudo_labeling/submit.sh --smoke 1    # 20 steps of arm 1, one GPU, 4 cubes
#
#   1  reset : every round re-initialises from the interpolation-trained encoder at 200k
#   2  warm  : every round warm-starts from the previous round's student
#
# The arms differ in one section of one file (see `diff 1a_reset_r1.toml 2a_warm_r1.toml`), so
# 1 vs 2 isolates the initialisation policy and nothing else.
#
# **The middle stage is new.** Every other experiment in this repo chains train -> train, where
# the dependency carries only a checkpoint path. Here it is train -> label -> train: the second
# training stage cannot start until a *dataset* has been generated by running the first stage's
# model over 100 unlabelled cubes. That job is CPU+GPU, writes sidecar containers under
# $STAGE/pseudo_<round>, and ends by emitting the miao config the next stage reads.
#
# Round 1's labels come from teacher_0, which both arms share, so they are generated ONCE and
# both arms train on the identical dataset. Only round 2 forks, because only then do the arms
# have different students to label with.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
VENV=/groups/scicompsoft/home/orhane/myvenv
BANIS=/groups/scicompsoft/home/orhane/projects/banis
PROJECT=miaai
RUNS=/nrs/scicompsoft/orhane/mia-train-runs
STAGE=/nrs/scicompsoft/orhane/mia-train-scratch/pseudo_labeling
LOGS="$RUNS/jobs"
mkdir -p "$LOGS" "$STAGE/cmd" "$STAGE/configs" "$STAGE/locks"

# teacher_0: the best checkpoint on this task, 0.4941 nERL whole-cube on seed100. Round 1's
# pseudo-labels are only as good as this model, and every later round inherits that ceiling.
TEACHER0="$RUNS/subpixel_decoder__subpixel_256_20260811_143947"
TEACHER0_STEP=100000

CUBES=${CUBES:-/groups/miaai/miaai/lmd-v0.0.1/dev/nisb/train_100/train}
N_CUBES=${N_CUBES:-100}
# **The whole cube, not a sample of it.** The original 2-blocks-of-384 budget was inherited from
# mutex watershed's ~7 us/voxel cost and never revisited after the switch to cc3d, and it left the
# experiment pseudo-labelling 0.93% of train_100 -- 0.19x the volume of real labels in `base`, with
# base offering 96x more distinct 256^3 crop centres than all 200 blocks combined. The premise was
# 20x MORE data than base; it was delivering a fifth as much.
#
# Storage was never the obstacle: these labels compress 21.8x (measured, 200x384^3 = 42 GB dense
# but 1.94 GB on disk), so all 100 cubes at full coverage are ~208 GB, not the 4.4 TB the dense
# figure suggests. The real cost is GPU prediction, which is why this runs on L4s.
BLOCKS=${BLOCKS:-2}          # only used when --full-cube is off
FULL_CUBE=${FULL_CUBE:-1}
# Max tile edge -> a 2x2x1 partition into 1500x1500x1350 tiles, 4 per cube.
#
# The ceiling is not memory, it is cc3d: `color_connectivity_graph` indexes in uint32 and rejects
# any region of 2^32 voxels or more before doing any work. Measured by bisection -- 1620^3 (4.252e9)
# passes, 1700^3 (4.913e9) fails; 3000x3000x450 passes, x500 fails. So one tile per whole cube is
# impossible at 1.215e10 voxels, 2.8x over, no matter how much RAM is thrown at it.
#
# 1500 is the best tile under that ceiling on every axis at once: 0.71x of the limit (comfortable
# margin), 82.3% of the cube's 256^3 crop centres reachable against 50.9% at target 1000, and 5,760
# patches per cube against 6,912 -- 17% CHEAPER, because fewer tiles means less margin re-prediction.
# Peak is ~141 GB for the build and ~100 GB for prediction with the slab-wise normalisation.
BLOCK=${BLOCK:-1500}
# 128, not 64. The margin has two jobs and they want different sizes: it must exceed the
# long-range offset (10) for the long-range affinity channels to be computed from real data at
# all, which 64 already did -- but it must also be at least the patch STRIDE for every voxel of
# the tile to be central to some patch. At stride 128 a voxel 64 from the read edge is only ever
# covered by patches where it sits near their edge, which is where the model is least reliable and
# exactly what the blending weight down-weights. ~8.5% of a cube lies within 64 of an internal
# seam, weak affinities there drop edges, and dropped edges are splits -- the failure mode that
# sank round 1. Costs 1440 -> 1690 patches per tile (+17%).
MARGIN=${MARGIN:-128}
# 0.2. This went 0.3 -> 0.5 -> 0.2, and the middle value was the wrong reaction to the wrong
# problem: 0.5 was a hedge against round 1's pseudo-labels being actively harmful, which they were
# -- but they were harmful because there were almost none of them (0.93% coverage) and they were
# over-fragmented (+7). With 100% coverage and +5 both fixed, leaning on 5 real cubes for half the
# gradient caps the contribution of the 107x more data we just generated.
#
# 0.2 also matches the method: NoisyStudent trains on 300M unlabelled against 1.3M labelled, with
# the unlabelled batch several times LARGER, not equal. And 0.2 still oversamples the real labels
# heavily relative to their number: 5 base cubes at 0.04 each against 100 pseudo cubes at 0.008
# each (4 tiles x 0.002), so a base cube is drawn 5x more often than any pseudo cube. It was 20x
# at GT_WEIGHT=0.5.
GT_WEIGHT=${GT_WEIGHT:-0.2}  # share of training samples drawn from real base labels

# Filter thresholds, from `mia_pseudolabel calibrate` over 6 blocks of seed100 (the benchmark's
# hyperparameter cube, which teacher_0 never trained on). Override from the environment rather
# than editing, so the run record shows what was used.
#
#   logit  coverage  merges  splits
#     +5     0.680       4     138
#     +6     0.626       1     144
#     +7     0.559       0     161      <- first zero-merge threshold
#     +8     0.486       0     177
#
# **+5, revised down from +7 after round 1 failed.** The original reasoning picked the first
# zero-merge threshold, on the grounds that a merge corrupts every pair spanning two fused neurons
# while a split misstates only one seam. That is true of individual targets and wrong about what a
# model learns from a whole distribution of them: +7's labels rendered a median 62 true objects as
# 305 fragments, and the student learned that fragmentation as a behaviour, then amplified it --
# 163 splits against teacher_0's 37 at a matched threshold, and 14.7% worse nERL than the teacher
# that trained it. Its round-2 labels were worse again, at 656 fragments.
#
# +5 has *fewer* splits and more merges than +7 (138/4 against 161/0 on the calibration blocks),
# and is also where teacher_0's own optimum sat. Trading a handful of merges for far less
# systematic over-splitting is the bet this round tests.
CC_LOGIT=${CC_LOGIT:-5}
TAU_BG=${TAU_BG:-0.40}
# Measured inert: any voxel CC labelled already exceeds this, so the band can only fire on voxels
# CC dropped. Kept at its measured value for the record rather than removed.
TAU_FG=${TAU_FG:-0.50}
# A tripwire, not a filter. It abstains where the long-range channels -- which CC never reads --
# confidently dispute a merge CC made. On teacher_0 it fires on ~0 voxels (over 6.2M merged pairs
# the 1st percentile long-range affinity is 0.763), which is a fact about this teacher, not a
# no-op by construction: `frac_disputed` in each block's stats reports what it caught. It is here
# for later rounds, where a student trained on its own pseudo-labels may become less coherent.
TAU_LONG=${TAU_LONG:-0.30}
MIN_SIZE=${MIN_SIZE:-200}

# H100 rather than H200: measured 9.5 samples/s against H200's 16.4, so a 10k stage is ~3 h
# instead of ~81 min. Wall time below is sized for the slower generation. Override with
# QUEUE=gpu_h200 when those free up again.
#
# Two GPUs and 24 slots, not a whole 96-slot node. A whole-node request is the thing that made
# this queue-bound: it needs 8 free GPUs *and* 96 free cores with matching affinity on one host,
# so it sat behind 700+ pending jobs for hours. Two GPUs dispatch in under two minutes, and there
# are essentially always two H200s free.
#
# It is also faster per GPU, which was not obvious in advance -- see `batch_size` in the stage
# configs for the measurement. Because the request is small and reliably satisfied, the twin-queue
# machinery this used to need is gone: one queue, one job per stage, no lock. `claim.sh` remains
# in the directory for reference but nothing submits through it.
GPUS=2
SLOTS=${SLOTS:-24}
QUEUE=${QUEUE:-gpu_h100}
# Labelling is sharded across cubes as an LSF array. Measured 82 s per cube, so 100 cubes is
# ~2.3 h in one job against ~15 min at 10 shards. `%N` caps how many elements run at once, which
# matters because each holds a GPU: the per-user limit is roughly half the queue, and stranding
# more than this starves everyone else's work for no gain -- the stage is not latency-critical.
# One cube per shard. Full-cube labelling is 6,912 patches per cube (32 tiles x 216), ~2.9 h on
# one L4 at the measured 1.5 s/patch, so 100 shards finish in about the time one cube takes.
SHARDS=${SHARDS:-100}
# Back to 100: with the fused `label` path there are no affinity files at all, so scratch usage is
# ~2 GB of labels per cube instead of 146 GB in flight. Concurrency is bound by GPUs again, which
# is where it belongs.
LABEL_CONCURRENT=${LABEL_CONCURRENT:-100}
# **L4, not A100.** Measured peak VRAM for a 256^3 inference patch is 6.1 GiB of the L4's 22, so
# the 24 GB card is never the constraint, and an L4 runs ~1.5 s/patch against the A100's ~1.0 --
# only 1.5x slower, while the L4 queues sit at 0 PEND when A100 and H100 are saturated. Throughput
# here comes from breadth, not per-card speed: 100 L4s beat 10 A100s by 6x and are actually
# available.
#
# `gpu_l4_16` rather than `gpu_l4`: same 8 L4s per node but 16 slots per GPU instead of 8, so a
# job gets 240 GB of host RAM rather than 120. That headroom is worth having here -- a 750^3 tile
# plus its collar needs a 17.3 GB float32 accumulator during blending and cc3d works in ~15 GB on
# top -- and it is the L4 queue with the deepest pool of running work, i.e. the most turnover.
#
# 16 slots is that queue's own per-GPU ratio, so one job per GPU exactly fills a node's 128 slots
# and strands nothing.
LABEL_QUEUE=${LABEL_QUEUE:-gpu_l4_16}
LABEL_SLOTS=${LABEL_SLOTS:-16}
THREADS="export OMP_NUM_THREADS=4 MKL_NUM_THREADS=4 OPENBLAS_NUM_THREADS=4"

SMOKE=0
[[ "${1:-}" == "--smoke" ]] && { SMOKE=1; shift; }
LABEL_ONLY=""
[[ "${1:-}" == "--label" ]] && { LABEL_ONLY=$2; shift 2; }
[[ $SMOKE -eq 1 ]] && { N_CUBES=4; BLOCKS=1; BLOCK=192; SHARDS=2; LABEL_CONCURRENT=2; }

FULL_FLAG=""; [[ "${FULL_CUBE:-0}" == "1" ]] && FULL_FLAG="--full-cube"

jobid () { sed -n 's/^Job <\([0-9]*\)>.*/\1/p'; }
# One id per stage now that stages are not twinned; the loop is kept so a future twin pair would
# still compose, and `||` is the correct join for that case.
dep_of () { local d=""; for id in "$@"; do d+="${d:+ || }done($id)"; done; echo "$d"; }

# label <round tag> <teacher run dir or PREV:experiment_suffix> <step or "latest"> [<dependency>]
#
# Two jobs. An **array** shards the cubes: element i takes every SHARDS-th cube and loads the
# teacher once for its whole slice -- one cube per element would spend ~30 s of every ~80 s
# reloading a 4.8 GB checkpoint. Elements are idempotent (a cube whose pseudolabel.json exists is
# skipped), so a requeue after a wall-clock kill or a single failed element resumes rather than
# restarts.
#
# A **finalise** job then writes the round's miao config and runs the oracle. Both need *every*
# cube's labels, so neither can live in a worker. It waits on done(<array>), which LSF satisfies
# only once all elements have finished, and it is what downstream stages depend on -- the training
# stage needs the config to exist, not merely the labels.
#
# Affinities are deleted per cube as soon as that cube's labels are built: at 6 channels of
# float16 a 384^3 block is 680 MB, so keeping all of them would cost ~136 GB per round for
# artifacts that exist only to be thresholded once.
label () {
  local tag=$1 teacher=$2 step=$3 dep=${4:-}
  local root="$STAGE/pseudo_$tag" cfg="$STAGE/configs/round_$tag.yaml"
  local worker="$STAGE/cmd/label_${tag}_worker.sh" final="$STAGE/cmd/label_${tag}_final.sh"

  { echo "#!/usr/bin/env bash"
    echo "set -euo pipefail"
    echo "$THREADS"
    # A PREV: teacher is another experiment's newest run, resolved in the job rather than at
    # submission time, because the run directory does not exist until its job has started. Each
    # element resolves independently and identically.
    if [[ "$teacher" == PREV:* ]]; then
      echo "RUN=\$(ls -dt $RUNS/pl__${teacher#PREV:}_*/ | head -1)"
      echo "STEP=\$(ls -d \${RUN}checkpoints/step_* | sed 's|.*step_||' | sort -n | tail -1)"
    else
      echo "RUN=$teacher/"
      echo "STEP=$step"
    fi
    echo "SHARD=\${LSB_JOBINDEX:-1}"
    echo "echo \"shard \$SHARD/$SHARDS labelling with \${RUN} step \$STEP\""
    echo "mkdir -p '$root'"
    echo "cd $BANIS"
    echo "$VENV/bin/python mia_pseudolabel.py self-test"
    # awk -v rather than interpolating into the awk program, so shell and awk quoting do not fight.
    echo "MINE=\$(ls -d $CUBES/seed*.zarr | sort -V | head -$N_CUBES | awk -v s=\$SHARD -v n=$SHARDS 'NR % n == s % n')"
    echo "echo \"shard \$SHARD handles \$(echo \"\$MINE\" | wc -l) cubes\""
    echo "for cube in \$MINE; do"
    echo "  name=\$(basename \$cube .zarr)"
    echo "  if [[ -f '$root'/\$name.zarr/pseudolabel.json ]]; then echo \"  \$name done\"; continue; fi"
    # One fused call per cube: predict and segment tile by tile, in one process, so a tile's
    # affinities live only as a numpy array. The old predict-all-then-build-all split held 4 x
    # 36.5 GB per cube on disk, which at 100 concurrent needed 14.6 TB and filled a shared 40 TB
    # filesystem on 2026-08-19, killing 67 of 100 jobs.
    echo "  $VENV/bin/python mia_pseudolabel.py label \"\$RUN\" --cube \$cube \\"
    echo "      --out '$root'/\$name.zarr --label-name pseudo_$tag --step \$STEP \\"
    echo "      --block $BLOCK --margin $MARGIN --patch 256 $FULL_FLAG \\"
    echo "      --cc-logit $CC_LOGIT --tau-bg $TAU_BG --tau-fg $TAU_FG \\"
    echo "      --tau-long $TAU_LONG --min-size $MIN_SIZE"
    echo "done"
  } > "$worker"

  { echo "#!/usr/bin/env bash"
    echo "set -euo pipefail"
    echo "$THREADS"
    # A partially-labelled round would train on less data than intended and confound the arms,
    # and make_round_config would happily build it. Fail loudly instead.
    echo "n=\$(ls -d '$root'/*.zarr/pseudolabel.json 2>/dev/null | wc -l)"
    echo "if [[ \$n -ne $N_CUBES ]]; then echo \"only \$n/$N_CUBES cubes labelled -- refusing to build a partial round\" >&2; exit 1; fi"
    echo "$VENV/bin/python $HERE/make_round_config.py --sidecar-root '$root' \\"
    echo "    --out '$cfg' --gt-weight $GT_WEIGHT --patch-size 256"
    # The oracle: score these pseudo-labels against the ground truth the experiment pretends not
    # to have. Read-only and after the fact -- nothing downstream reads it, and nothing may, or
    # the labels have leaked and the round stops simulating an unlabelled dataset.
    echo "$VENV/bin/python $BANIS/mia_pseudolabel.py oracle --sidecar-root '$root' \\"
    echo "    --out '$STAGE/configs/oracle_$tag.json' || echo 'oracle failed (non-fatal)'"
  } > "$final"
  chmod +x "$worker" "$final"

  local arr fin
  arr=$(bsub -P "$PROJECT" -q "$LABEL_QUEUE" -gpu "num=1" -n "$LABEL_SLOTS" -W "${LABEL_WALL:-4:00}" -r \
    ${dep:+-w "$dep"} -J "pl_label_${tag}[1-$SHARDS]%$LABEL_CONCURRENT" -cwd "$REPO" \
    -o "$LOGS/pl_label_${tag}_%J_%I.log" -e "$LOGS/pl_label_${tag}_%J_%I.err" "$worker" | jobid)
  # CPU queue: the finalise step is numpy and zarr, and holding a GPU through it is waste.
  fin=$(bsub -P "$PROJECT" -q local -n 4 -W 2:00 \
    -w "done($arr)" -J "pl_label_${tag}_fin" -cwd "$REPO" \
    -o "$LOGS/pl_label_${tag}_fin_%J.log" -e "$LOGS/pl_label_${tag}_fin_%J.err" "$final" | jobid)
  echo "    array $arr[1-$SHARDS]%$LABEL_CONCURRENT -> finalise $fin" >&2
  echo "$fin"
}

# stage <config> <round tag> <wall> [<predecessor suffix for PREV_CHECKPOINT>] [<dependency>]
stage () {
  local config=$1 round=$2 wall=$3 prev=${4:-} dep=${5:-}
  local name; name=$(basename "$config" .toml)
  local tag=$name procs=$GPUS slots=$SLOTS cfg="$config" prologue=""
  local roundcfg="$STAGE/configs/round_$round.yaml"

  if [[ $SMOKE -eq 1 ]]; then
    tag="smoke_$name"; wall=0:30; procs=1; slots=12
    cfg="$STAGE/$tag.toml"
    sed -e "s/^experiment_name = .*/experiment_name = \"$tag\"/" \
        -e 's/^max_steps = .*/max_steps = 20/' -e 's/^warmup_steps = .*/warmup_steps = 2/' \
        -e 's/^val_every = .*/val_every = 10/' -e 's/^checkpoint_every = .*/checkpoint_every = 20/' \
        -e 's/^samples_per_epoch = .*/samples_per_epoch = 20/' -e 's/^dp_shard = .*/dp_shard = 1/' \
        "$config" > "$cfg"
  fi

  local resolved="$STAGE/${tag}_resolved.toml"
  prologue="sed \"s|ROUND_CONFIG|$roundcfg|\" '$cfg' > '$resolved'"
  if [[ -n "$prev" ]]; then
    prologue="RUN=\$(ls -dt $RUNS/pl__${prev}_*/ | head -1)
STEP=\$(ls -d \${RUN}checkpoints/step_* | sed 's|.*step_||' | sort -n | tail -1)
echo \"initialising from \${RUN}checkpoints/step_\$STEP\"
sed -e \"s|ROUND_CONFIG|$roundcfg|\" -e \"s|PREV_CHECKPOINT|\${RUN}checkpoints/step_\$STEP|\" '$cfg' > '$resolved'"
  fi

  local cmd="$STAGE/cmd/${tag}.sh"
  { echo "#!/usr/bin/env bash"
    echo "set -euo pipefail"
    echo "$THREADS"
    echo "export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True"
    echo "$prologue"
    printf '%s --standalone --nproc_per_node=%s src/train.py --config %q %s\n' \
      "$VENV/bin/torchrun" "$procs" "$resolved" \
      "$([[ $SMOKE -eq 1 ]] && printf -- "--output-root %q" "$STAGE/smoke" || echo "--resume")"
  } > "$cmd"
  chmod +x "$cmd"

  bsub -P "$PROJECT" -q "$QUEUE" -gpu "num=$procs" -n "$slots" -W "$wall" -r \
    ${dep:+-w "$dep"} -J "pl_$tag" -cwd "$REPO" \
    -o "$LOGS/pl_${tag}_%J.log" -e "$LOGS/pl_${tag}_%J.err" "$cmd" | jobid
}

report () { printf "%-24s job %s\n" "$1" "$2"; }

if [[ -n "$LABEL_ONLY" ]]; then
  report "label_$LABEL_ONLY" "$(label "$LABEL_ONLY" "$TEACHER0" "$TEACHER0_STEP")"
  exit 0
fi

# Round 1's labels are shared by both arms: teacher_0 is the same model for each, so labelling
# twice would burn a GPU-day to produce two identical datasets.
#
# They are also independent of every training hyperparameter, so re-tuning the student's recipe
# must not redo them. Skipped when the round is *complete* by the same condition the finalise job
# enforces -- all N cubes labelled and the config written -- so a half-finished round still
# reruns. FORCE_RELABEL=1 overrides, e.g. after changing a filter threshold.
labels_ready () {
  [[ "${FORCE_RELABEL:-0}" == "1" ]] && return 1
  [[ -f "$2" ]] || return 1
  [[ "$(ls -d "$1"/*.zarr/pseudolabel.json 2>/dev/null | wc -l)" -eq "$N_CUBES" ]]
}

if labels_ready "$STAGE/pseudo_r1" "$STAGE/configs/round_r1.yaml"; then
  L1=""
  report label_r1 "already complete ($N_CUBES cubes) -- skipped"
else
  L1=$(label r1 "$TEACHER0" "$TEACHER0_STEP"); report label_r1 "$L1"
fi

ARMS=("$@"); [[ ${#ARMS[@]} -gt 0 ]] || ARMS=(1 2)
for arm in "${ARMS[@]}"; do
  case $arm in
    1) a=$(stage "$HERE/1a_reset_r1.toml" r1 6:00 "" "$(dep_of $L1)"); report 1a_reset_r1 "$a"
       l=$(label r2_reset "PREV:1a_reset_r1" latest "$(dep_of $a)"); report label_r2_reset "$l"
       b=$(stage "$HERE/1b_reset_r2.toml" r2_reset 6:00 "" "$(dep_of $l)"); report 1b_reset_r2 "$b" ;;
    2) a=$(stage "$HERE/2a_warm_r1.toml" r1 6:00 "" "$(dep_of $L1)"); report 2a_warm_r1 "$a"
       l=$(label r2_warm "PREV:2a_warm_r1" latest "$(dep_of $a)"); report label_r2_warm "$l"
       b=$(stage "$HERE/2b_warm_r2.toml" r2_warm 6:00 2a_warm_r1 "$(dep_of $l)"); report 2b_warm_r2 "$b" ;;
    *) echo "unknown arm: $arm (expected 1 or 2)" >&2; exit 2 ;;
  esac
done
